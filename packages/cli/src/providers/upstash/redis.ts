import { registerUndo, type Change, type Context } from "../../core/plan.ts";
import { writeGenerated } from "../../core/files.ts";
import { state, type Resource } from "../../core/state.ts";
import { vault } from "../../core/vault.ts";
import { keychain, listConnections } from "../../store.ts";
import { restUrl, Upstash } from "./api.ts";

export interface RedisInput {
  name: string;
  region: string;
  plan: string;
  budget?: number;
}

/** Agents can pass UPSTASH_EMAIL + UPSTASH_API_KEY; otherwise use the account from `sikrets connect upstash`. */
export async function upstashClient() {
  if (process.env.UPSTASH_EMAIL && process.env.UPSTASH_API_KEY) {
    return { api: new Upstash(process.env.UPSTASH_EMAIL, process.env.UPSTASH_API_KEY), account: process.env.UPSTASH_EMAIL };
  }
  const conn = (await listConnections()).find((c) => c.provider === "upstash");
  const key = conn && (await keychain.get("upstash", `${conn.account}#api-key`));
  if (!conn || !key) throw new Error("Upstash isn't connected. Run: sikrets connect upstash");
  return { api: new Upstash(conn.account, key), account: conn.account };
}

const envKey = (name: string, suffix: string) => `${name.toUpperCase().replace(/[^A-Z0-9]/g, "_")}_${suffix}`;
const tfName = (name: string) => name.replace(/[^A-Za-z0-9_]/g, "_");

/** Read-only: looks at the account and describes every change, without making any. */
export async function planRedis(input: RedisInput, ctx: Context): Promise<Change[]> {
  const { api, account } = await upstashClient();
  if ((await api.listDatabases()).some((d) => d.database_name === input.name)) {
    throw new Error(`An Upstash database named "${input.name}" already exists in ${account}`);
  }
  const id = `upstash/redis/${input.name}`;
  const urlKey = envKey(input.name, "REDIS_REST_URL");
  const tokenKey = envKey(input.name, "REDIS_REST_TOKEN");
  const iacFile = `iac/terraform/upstash-${input.name}.tf`;
  const cost =
    input.plan === "free" ? "free tier" : input.plan === "payg" ? `pay as you go${input.budget ? `, capped at $${input.budget}/mo` : ", no budget cap"}` : `${input.plan} fixed plan`;

  let created: { id: string; url: string; token: string } | undefined;

  return [
    {
      summary: `Upstash Redis "${input.name}" in aws/${input.region} on account ${account}`,
      cost,
      async apply() {
        const db = await api.createDatabase({ database_name: input.name, platform: "aws", primary_region: input.region, plan: input.plan, budget: input.budget, tls: true });
        if (!db.rest_token) throw new Error("Upstash didn't return a REST token (is credential protection on?)");
        created = { id: db.database_id, url: restUrl(db.endpoint), token: db.rest_token };
        return { kind: "upstash.redis.delete", summary: `Delete Upstash Redis "${input.name}"`, data: { id: db.database_id, name: input.name } };
      },
    },
    {
      summary: `Store ${urlKey} and ${tokenKey} in the keychain vault for ${ctx.project}`,
      async apply(c) {
        await vault.set(c.project, urlKey, created!.url);
        await vault.set(c.project, tokenKey, created!.token);
        return { kind: "vault.delete", summary: `Remove ${urlKey}, ${tokenKey} from the vault`, data: { project: c.project, keys: `${urlKey},${tokenKey}` } };
      },
    },
    {
      summary: `Generate ${iacFile} (imports the database into Terraform)`,
      async apply(c) {
        await writeGenerated(c.root, iacFile, terraform(input, created!.id));
        return { kind: "file.delete", summary: `Remove ${iacFile}`, data: { path: iacFile } };
      },
    },
    {
      summary: `Record ${id} in .sikrets/state.json`,
      async apply(c) {
        const resource: Resource = {
          id, provider: "upstash", service: "redis", name: input.name, remoteId: created!.id, account,
          plan: input.plan, budget: input.budget, envKeys: [urlKey, tokenKey], createdAt: new Date().toISOString(),
        };
        await state.upsert(c.root, resource);
        return { kind: "state.remove", summary: `Forget ${id}`, data: { id } };
      },
    },
  ];
}

// Credentials reach Terraform only through `sikrets run -- terraform …` (UPSTASH_EMAIL / UPSTASH_API_KEY).
function terraform(input: RedisInput, remoteId: string) {
  const r = tfName(input.name);
  return `# Generated by Sikrets. Edit freely — Sikrets won't overwrite or delete a file you've changed.
# Run with: sikrets run -- terraform plan

terraform {
  required_providers {
    upstash = { source = "upstash/upstash" }
  }
}

provider "upstash" {}

import {
  to = upstash_redis_database.${r}
  id = "${remoteId}"
}

resource "upstash_redis_database" "${r}" {
  database_name  = "${input.name}"
  region         = "global"
  primary_region = "${input.region}"
  tls            = true
}
`;
}

export async function redisCost(resource: Resource) {
  const { api } = await upstashClient();
  const s = await api.stats(resource.remoteId);
  return s.total_monthly_billing ?? 0;
}

registerUndo("upstash.redis.delete", async ({ id }) => {
  const { api } = await upstashClient();
  await api.deleteDatabase(id!);
});
registerUndo("state.remove", async ({ id }, ctx) => state.remove(ctx.root, id!));
