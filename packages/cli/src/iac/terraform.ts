import type { Resource } from "../core/state.ts";
import { terraformRecipe } from "../recipes/index.ts";
import { moduleSlug, tfIdent, type TerraformRecipe } from "../recipes/types.ts";

// Layout under iac/terraform/ — additive, so each add only creates files and rollback only removes
// its own:
//   versions.tf                     providers in use (regenerated)
//   <resource>.tf                   module call + outputs for one resource
//   modules/<recipe>/{main,variables,outputs}.tf   shared by every resource of that recipe

export const IAC_DIR = "iac/terraform";
export const files = {
  versions: `${IAC_DIR}/versions.tf`,
  root: (name: string) => `${IAC_DIR}/${name}.tf`,
  module: (r: TerraformRecipe) => ["main", "variables", "outputs"].map((f) => `${IAC_DIR}/modules/${moduleSlug(r.id)}/${f}.tf`) as [string, string, string],
};

/** Root output name for one resource output; `sikrets sync` reads these back. */
export const outputName = (resource: string, key: string) => `${tfIdent(resource)}__${key}`;

const HEADER = "# Generated by Sikrets. Edit freely: Sikrets won't overwrite or delete a file you've changed.\n";

export function versionsTf(resources: readonly Resource[]): string {
  const sources = [...new Set(resources.filter((r) => r.strategy === "terraform").map((r) => terraformRecipe(r.recipe).terraformProvider))].sort();
  const lines = sources.map((s) => `    ${s.split("/")[1]} = { source = "${s}" }`);
  // Credentials and region reach providers through the environment that `sikrets apply` builds.
  return `${HEADER}
terraform {
  required_providers {
${lines.join("\n")}
  }
}
${sources.map((s) => `\nprovider "${s.split("/")[1]}" {}`).join("")}
`;
}

export function rootTf(resource: Resource): string {
  const r = terraformRecipe(resource.recipe);
  const dep = (as: string, output: string) => {
    const target = resource.dependsOn[as];
    if (!target) throw new Error(`${resource.name} has no dependency named "${as}"`);
    return `module.${tfIdent(target)}.${output}`;
  };
  const args = { ...r.arguments(resource.inputs, dep), name: JSON.stringify(resource.name) };
  const width = Math.max(...Object.keys(args).map((k) => k.length), "source".length);
  const body = [`  ${"source".padEnd(width)} = "./modules/${moduleSlug(r.id)}"`, ...Object.entries(args).map(([k, v]) => `  ${k.padEnd(width)} = ${v}`)];
  const outputs = Object.entries(r.outputs).map(
    ([key, spec]) =>
      `output "${outputName(resource.name, key)}" {\n  value = module.${tfIdent(resource.name)}.${key}${spec.sensitive ? "\n  sensitive = true" : ""}\n}`,
  );
  return `${HEADER}# ${r.id}: ${r.summary}\n\nmodule "${tfIdent(resource.name)}" {\n${body.join("\n")}\n}\n\n${outputs.join("\n\n")}\n`;
}

export const moduleTf = (r: TerraformRecipe): [string, string, string] => [HEADER + r.module.main, HEADER + r.module.variables, HEADER + r.module.outputs];

/** Terraform state holds secret values in plain text; keep it and local caches out of git. */
export const GITIGNORE = [`${IAC_DIR}/.terraform/`, `${IAC_DIR}/*.tfstate`, `${IAC_DIR}/*.tfstate.*`, `${IAC_DIR}/*.tfplan`, ".env", ".env.*"];
